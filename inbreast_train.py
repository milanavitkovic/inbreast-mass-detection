def sanity_check(train_df, img_dir, device, seed=42):
    """Quick sanity check: can model overfit on 10 samples?"""
    print("\n" + "=" * 80)
    print("6️⃣ SANITY CHECK: 10 images")
    print("=" * 80)

    sanity_train = pd.concat([
        train_df[train_df['label'] == 0].head(5),
        train_df[train_df['label'] == 1].head(5)
    ]).reset_index(drop=True)

    sanity_ds = INBreastDataset(sanity_train, img_dir, transform=get_transforms(train=False, augment=False))
    sanity_loader = DataLoader(sanity_ds, batch_size=10, shuffle=False)

    model = models.resnet34(pretrained=True)
    model.fc = nn.Linear(512, 2)
    model = model.to(device)

    optimizer = torch.optim.SGD(model.parameters(), lr=0.01, momentum=0.9)
    criterion = nn.CrossEntropyLoss()

    print(f"Sanity dataset: {len(sanity_train)} images")

    first_100 = None
    consecutive_100 = 0
    max_consecutive = 0

    for epoch in range(1, 51):
        model.train()
        total_loss, correct, total = 0, 0, 0

        for images, labels in sanity_loader:
            images, labels = images.to(device), labels.to(device)

            optimizer.zero_grad()
            outputs = model(images)
            loss = criterion(outputs, labels)
            loss.backward()
            optimizer.step()

            total_loss += loss.item() * images.size(0)
            _, preds = outputs.max(1)
            total += labels.size(0)
            correct += preds.eq(labels).sum().item()

        acc = 100. * correct / total

        if acc == 100.0:
            if first_100 is None:
                first_100 = epoch
            consecutive_100 += 1
            max_consecutive = max(max_consecutive, consecutive_100)
        else:
            consecutive_100 = 0

        if epoch % 10 == 0 or epoch <= 5 or epoch == 50:
            print(f"Epoch {epoch:02d}/50 | Loss: {total_loss/total:.4f} | Acc: {acc:.1f}%")

    print()
    if first_100 is not None and max_consecutive >= 10:
        print(f"✅ SANITY CHECK PASSED! (epoch {first_100}, stability {max_consecutive})")
    else:
        print(f"⚠️ SANITY CHECK WARNING: max_acc={acc:.1f}%")

    del model, optimizer, criterion
    torch.cuda.empty_cache()


