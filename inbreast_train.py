def apply_clahe(img):
    """Apply Contrast Limited Adaptive Histogram Equalization"""
    clahe = cv2.createCLAHE(clipLimit=3.0, tileGridSize=(8, 8))
    return clahe.apply(img)


def apply_histogram_equalization(img):
    """Apply standard histogram equalization"""
    return cv2.equalizeHist(img)


def apply_unsharp_mask(img):
    """Apply unsharp masking for edge enhancement"""
    gaussian = cv2.GaussianBlur(img, (5, 5), 2.0)
    sharpened = cv2.addWeighted(img, 1.5, gaussian, -0.5, 0)
    return np.clip(sharpened, 0, 255).astype(np.uint8)


def preprocess_image_advanced(img):
    """
    Main preprocessing pipeline: Min-Max normalization + CLAHE + Unsharp Masking

    Args:
        img: Input grayscale image (any dtype)

    Returns:
        Preprocessed image (uint8)
    """
    # Step 1: Min-Max normalization to [0, 255]
    img_norm = ((img - img.min()) / (img.max() - img.min() + 1e-8) * 255).astype(np.uint8)

    # Step 2: CLAHE for local contrast enhancement
    img_clahe = apply_clahe(img_norm)

    # Step 3: Unsharp masking for edge enhancement
    img_sharp = apply_unsharp_mask(img_clahe)

    return img_sharp


