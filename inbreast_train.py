def load_data(excel_path, img_dir):
    """Load and prepare dataset from Excel file"""
    print("=" * 80)
    print("1️⃣  LOADING DATA")
    print("=" * 80)

    if not os.path.exists(excel_path):
        raise FileNotFoundError(f"Excel file not found: {excel_path}")

    df = pd.read_excel(excel_path)
    df['label'] = (df['Mass '] == 1).astype(int)

    def exists(row):
        try:
            fname = f"{int(row['File Name'])}_{row['Patient ID']}_MG_{row['Laterality']}_{row['View']}.png"
            return os.path.isfile(os.path.join(img_dir, fname))
        except:
            return False

    df['exists'] = df.apply(exists, axis=1)
    df = df[df['exists']].reset_index(drop=True)

    print(f"✓ Loaded {len(df)} images from {df['Patient ID'].nunique()} patients")
    print(f"\nClass Distribution:")
    print(f"  0 (No Mass):  {(df['label']==0).sum()} images")
    print(f"  1 (Has Mass): {(df['label']==1).sum()} images")

    return df


