def split_data(df, seed=42):
    """Split data by patient ID to prevent data leakage"""
    print("\n" + "=" * 80)
    print("3️⃣ DATA SPLITTING: 80/10/10")
    print("=" * 80)

    patients = df['Patient ID'].unique()
    train_pts, temp_pts = train_test_split(patients, test_size=0.2, random_state=seed)
    val_pts, test_pts = train_test_split(temp_pts, test_size=0.5, random_state=seed)

    train_df = df[df['Patient ID'].isin(train_pts)].reset_index(drop=True)
    val_df = df[df['Patient ID'].isin(val_pts)].reset_index(drop=True)
    test_df = df[df['Patient ID'].isin(test_pts)].reset_index(drop=True)

    print(f"Train: {len(train_df)} images - {dict(train_df['label'].value_counts().sort_index())}")
    print(f"Val:   {len(val_df)} images - {dict(val_df['label'].value_counts().sort_index())}")
    print(f"Test:  {len(test_df)} images - {dict(test_df['label'].value_counts().sort_index())}")

    return train_df, val_df, test_df


