class INBreastDataset(Dataset):
    """
    Custom dataset for INBreast mammography images with advanced preprocessing
    """

    def __init__(self, df, img_dir, transform=None):
        """
        Args:
            df: DataFrame with columns ['File Name', 'Patient ID', 'Laterality', 'View', 'label']
            img_dir: Directory containing images
            transform: Albumentations transforms
        """
        self.df = df.reset_index(drop=True)
        self.img_dir = img_dir
        self.transform = transform

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]

        # Construct filename
        fname = f"{int(row['File Name'])}_{row['Patient ID']}_MG_{row['Laterality']}_{row['View']}.png"
        img_path = os.path.join(self.img_dir, fname)

        # Load image
        img = imread(img_path)

        # Apply advanced preprocessing (CLAHE + Unsharp Masking)
        img_processed = preprocess_image_advanced(img)

        # Convert to 3 channels for pretrained models
        image = np.stack((img_processed, img_processed, img_processed), axis=2)

        # Flip right laterality images for consistency
        if row['Laterality'] == 'R':
            image = np.fliplr(image).copy()

        # Apply augmentations and normalization
        if self.transform:
            image = self.transform(image=image)['image']

        label = torch.tensor(row['label'], dtype=torch.long)

        return image, label


