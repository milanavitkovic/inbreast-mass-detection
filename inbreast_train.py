def get_transforms(train=True, augment=True):
    """
    Get image transformations for training or validation

    Args:
        train: Whether these are training transforms
        augment: Whether to apply data augmentation

    Returns:
        Albumentations composition of transforms
    """
    transforms_list = [A.Resize(448, 448)]

    if train and augment:
        transforms_list += [
            A.HorizontalFlip(p=0.5),
            A.VerticalFlip(p=0.3),
            A.ShiftScaleRotate(shift_limit=0.1, scale_limit=0.15, rotate_limit=20, p=0.6),
            A.RandomBrightnessContrast(brightness_limit=0.3, contrast_limit=0.3, p=0.5),
            A.GaussNoise(var_limit=(10.0, 50.0), p=0.3),
            A.ElasticTransform(alpha=1, sigma=50, p=0.3),
        ]

    transforms_list += [
        A.Normalize(mean=MEAN, std=STD),
        ToTensorV2()
    ]

    return A.Compose(transforms_list)


