def visualize_predictions(model, test_df, img_dir, device, seed=42, n_samples=8):
    """Visualize model predictions on test samples"""
    print("\n" + "=" * 80)
    print("🔍 TEST PREDICTIONS VISUALIZATION")
    print("=" * 80)

    os.makedirs('results', exist_ok=True)

    test_samples = test_df.sample(n_samples, random_state=seed)
    test_sample_ds = INBreastDataset(test_samples, img_dir, transform=get_transforms(train=False, augment=False))
    test_sample_loader = DataLoader(test_sample_ds, batch_size=n_samples, shuffle=False)

    images_test, labels_test = next(iter(test_sample_loader))

    model.eval()
    with torch.no_grad():
        outputs = model(images_test.to(device))
        probs = torch.softmax(outputs, dim=1)
        preds = outputs.argmax(1).cpu().numpy()

    fig, axes = plt.subplots(2, 4, figsize=(16, 8))
    axes = axes.flatten()

    class_names = ['No Mass', 'Has Mass']

    for i in range(n_samples):
        # Denormalize image
        img_denorm = images_test[i] * STD + MEAN
        img_denorm = img_denorm.clamp(0, 1)
        img_np = img_denorm.permute(1, 2, 0).numpy()

        true_label = labels_test[i].item()
        pred_label = preds[i]
        confidence = probs[i][pred_label].item() * 100

        color = 'green' if true_label == pred_label else 'red'

        axes[i].imshow(img_np[:, :, 0], cmap='gray')
        axes[i].set_title(f"True: {class_names[true_label]}\nPred: {class_names[pred_label]} ({confidence:.1f}%)",
                         color=color, fontweight='bold')
        axes[i].axis('off')

    plt.tight_layout()
    plt.savefig('results/test_predictions.png', dpi=150, bbox_inches='tight')
    plt.close()
    print("✓ Prediction visualization saved to results/test_predictions.png")


