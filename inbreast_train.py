def train_model(model, train_loader, val_loader, criterion, optimizer, scheduler,
                device, epochs=80):
    """Train the model"""
    print("\n" + "=" * 80)
    print(f"8️⃣ TRAINING: {epochs} epochs with Focal Loss")
    print("=" * 80)

    history = {
        'train_loss': [], 'train_acc': [], 'train_f1': [],
        'val_loss': [], 'val_acc': [], 'val_f1': []
    }
    best_val_f1 = 0
    best_model_state = None
    best_epoch = 0

    for epoch in range(1, epochs + 1):
        # TRAIN
        model.train()
        train_loss, correct, total = 0, 0, 0
        train_preds_list, train_labels_list = [], []

        pbar = tqdm(train_loader, desc=f"Epoch {epoch}/{epochs}", leave=False)
        for images, labels in pbar:
            images, labels = images.to(device), labels.to(device)

            optimizer.zero_grad()
            outputs = model(images)
            loss = criterion(outputs, labels)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            optimizer.step()

            train_loss += loss.item() * images.size(0)
            _, preds = outputs.max(1)
            total += labels.size(0)
            correct += preds.eq(labels).sum().item()

            train_preds_list.extend(preds.cpu().numpy())
            train_labels_list.extend(labels.cpu().numpy())

            pbar.set_postfix({'loss': f'{loss.item():.3f}'})

        train_loss /= total
        train_acc = 100. * correct / total
        train_f1 = f1_score(train_labels_list, train_preds_list, average='binary', zero_division=0)

        # VALIDATION
        model.eval()
        val_loss, val_correct, val_total = 0, 0, 0
        val_preds_list, val_labels_list = [], []

        with torch.no_grad():
            for images, labels in val_loader:
                images, labels = images.to(device), labels.to(device)
                outputs = model(images)
                loss = criterion(outputs, labels)

                val_loss += loss.item() * images.size(0)
                _, preds = outputs.max(1)
                val_total += labels.size(0)
                val_correct += preds.eq(labels).sum().item()

                val_preds_list.extend(preds.cpu().numpy())
                val_labels_list.extend(labels.cpu().numpy())

        val_loss /= val_total
        val_acc = 100. * val_correct / val_total
        val_f1 = f1_score(val_labels_list, val_preds_list, average='binary', zero_division=0)

        scheduler.step()

        # Save best model
        if val_f1 > best_val_f1:
            best_val_f1 = val_f1
            best_epoch = epoch
            best_model_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}

        # Update history
        history['train_loss'].append(train_loss)
        history['train_acc'].append(train_acc)
        history['train_f1'].append(train_f1)
        history['val_loss'].append(val_loss)
        history['val_acc'].append(val_acc)
        history['val_f1'].append(val_f1)

        # Print progress
        unique_val = len(set(val_preds_list))
        status = "✓" if unique_val > 1 else f"⚠️ Only {unique_val} class"

        print(f"E{epoch:02d} | TrL:{train_loss:.3f} TrA:{train_acc:5.1f}% TrF1:{train_f1:.3f} | "
              f"VaL:{val_loss:.3f} VaA:{val_acc:5.1f}% VaF1:{val_f1:.3f} {status}")

    print(f"\n🏆 Best model: epoch {best_epoch}, val_f1={best_val_f1:.4f}")

    # Load best model
    model.load_state_dict(best_model_state)

    # Save model
    os.makedirs('models', exist_ok=True)
    torch.save({
        'epoch': best_epoch,
        'model_state_dict': best_model_state,
        'val_f1': best_val_f1,
        'history': history
    }, 'models/best_model.pth')
    print(f"✓ Model saved to models/best_model.pth")

    return model, history, best_epoch


