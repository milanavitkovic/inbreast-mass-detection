def main(args):
    """Main training pipeline"""
    # Setup
    print(f"Using device: {device}")
    seed_everything(args.seed)

    # Create output directories
    os.makedirs('results', exist_ok=True)
    os.makedirs('models', exist_ok=True)

    # Load data
    df = load_data(args.excel_path, args.img_dir)

    # Visualize preprocessing (optional)
    if args.visualize:
        visualize_preprocessing(df, args.img_dir, args.seed)

    # Split data
    train_df, val_df, test_df = split_data(df, args.seed)

    # Sanity check (optional)
    if args.sanity_check:
        sanity_check(train_df, args.img_dir, device, args.seed)

    # Compute class weights
    print("\n" + "=" * 80)
    print("5️⃣ CLASS WEIGHTS")
    print("=" * 80)

    class_weights = compute_class_weight(
        'balanced',
        classes=np.unique(train_df['label']),
        y=train_df['label']
    )
    class_weights = torch.FloatTensor(class_weights).to(device)

    print(f"Class 0 (No Mass):  {class_weights[0]:.4f}")
    print(f"Class 1 (Has Mass): {class_weights[1]:.4f}")
    print(f"Ratio: {class_weights[1]/class_weights[0]:.2f}x")

    # Create datasets
    train_ds = INBreastDataset(train_df, args.img_dir, transform=get_transforms(train=True, augment=True))
    val_ds = INBreastDataset(val_df, args.img_dir, transform=get_transforms(train=False, augment=False))
    test_ds = INBreastDataset(test_df, args.img_dir, transform=get_transforms(train=False, augment=False))

    train_loader = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True,
                              num_workers=args.num_workers, pin_memory=True)
    val_loader = DataLoader(val_ds, batch_size=args.batch_size, shuffle=False,
                           num_workers=args.num_workers, pin_memory=True)
    test_loader = DataLoader(test_ds, batch_size=16, shuffle=False)

    print(f"\nTrain: {len(train_ds)} images")
    print(f"Val:   {len(val_ds)} images")
    print(f"Test:  {len(test_ds)} images")

    # Visualize augmentations (optional)
    if args.visualize:
        visualize_augmentations(train_ds, n_samples=8)

    # Create model
    model = create_model(device)

    # Setup training
    print(f"🔥 Using FOCAL LOSS (alpha=0.25, gamma=2.0)")
    criterion = FocalLoss(alpha=0.25, gamma=2.0, weight=class_weights)

    optimizer = torch.optim.AdamW([
        {'params': model.layer4.parameters(), 'lr': 5e-4},
        {'params': model.layer3.parameters(), 'lr': 2e-4},
        {'params': model.layer2.parameters(), 'lr': 1e-4},
        {'params': model.fc.parameters(), 'lr': 1e-3}
    ], weight_decay=1e-4)

    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(
        optimizer, T_max=args.epochs, eta_min=1e-6
    )

    # Train
    model, history, best_epoch = train_model(
        model, train_loader, val_loader, criterion, optimizer, scheduler,
        device, epochs=args.epochs
    )

    # Plot training curves
    plot_training_curves(history, best_epoch)

    # Evaluate
    test_acc, test_f1, test_preds, test_labels = evaluate_model(model, test_loader, device)

    # Visualize predictions (optional)
    if args.visualize:
        visualize_predictions(model, test_df, args.img_dir, device, args.seed)

    # Final message
    print("\n" + "=" * 80)
    print("✅ TRAINING COMPLETE WITH CLAHE + UNSHARP MASKING!")
    print("=" * 80)
    print(f"🎯 Test F1:  {test_f1:.4f}")
    print(f"🎯 Test Acc: {test_acc*100:.2f}%")
    if test_f1 >= 0.85:
        print("🎉 EXCELLENT RESULTS!")
    elif test_f1 >= 0.75:
        print("✓ Good results!")
    else:
        print("⚠️ Room for improvement - consider stronger augmentations")
    print("=" * 80)


